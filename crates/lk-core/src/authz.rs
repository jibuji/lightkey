//! Agent 授权门（规格：`docs/authorization-gate.md`）。
//!
//! 设计要点（均为决议拍板，勿自行变更）：
//!
//! - 三层模型：**默认拒绝 → 规则白名单 → 弹窗审批**（30s 超时默认拒绝）。
//! - 启动者判定 = 进程链回溯 + 工作目录；agent 只能看到被授权的 key 名。
//! - 规则库：vault 内加密、按项目目录绑定；写入走 `lk rule add` / 桌面规则页，
//!   不开放手动改加密文件。
//! - 审批通道抽象成接口（本地/远程可切换；远程=未来付费点，P1 不做）。
//! - `lk inject`：给具名命令注入环境变量；密钥只注入被批准命令进程环境，
//!   不进模型对话环境。
//!
//! 占位模块：M2 起在此实现。
